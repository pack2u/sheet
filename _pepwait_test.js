let 잰것 = 0, 틀린것 = 0;
function ok(이름, 참, 덧) {
  잰것++;
  if (참) { console.log("  ok   " + 이름); return; }
  틀린것++;
  console.log("  FAIL " + 이름 + (덧 ? "  — " + 덧 : ""));
}
function 같나(이름, 얻은, 기대) {
  ok(이름, 얻은 === 기대, "얻은 " + JSON.stringify(얻은) + " · 기대 " + JSON.stringify(기대));
}

/** 임시기록 한 줄 — A 상태 · B 순번 · D 품목코드 · P(15) 고유ID · X(23) 송장 · Y(24) 진행상태 */
function 줄(순번, 코드, 고유ID, 송장, 진행상태) {
  const r = new Array(26).fill("");
  r[0] = ""; r[1] = 순번; r[2] = "2026/10/06 -21";
  r[3] = 코드; r[4] = "품목 " + 코드;
  r[15] = 고유ID;
  r[_PO_TEMP_INV_COL_] = 송장 || "";
  r[_PO_TEMP_STATUS_COL_] = 진행상태;
  return r;
}

