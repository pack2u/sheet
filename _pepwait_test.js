const fs = require("fs");
const path = require("path");

const 글 = fs.readFileSync(path.join(__dirname, "_partnerExclusivePush.gs"), "utf8");

function 꺼내(이름) {
  const i = 글.indexOf("function " + 이름 + "(");
  if (i < 0) throw new Error(이름 + " 를 못 찾았습니다");
  const j = 글.indexOf("{", i);
  let d = 0;
  for (let k = j; k < 글.length; k++) {
    if (글[k] === "{") d++;
    else if (글[k] === "}") { d--; if (!d) return 글.slice(i, k + 1); }
  }
  throw new Error(이름 + " 끝을 못 찾았습니다");
}

//  시트 상수 두 개와 함수 하나만 떼어 돌린다
