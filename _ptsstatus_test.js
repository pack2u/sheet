/**
 * ══════════════════════════════════════════════════════════════
 *  거래명세서 — 접수완료 · 발송완료 건만 싣는다
 *  2026-10-08
 *
 *  > "거래명세서 발행시 우리 접수완료, 발송완료건들만 거래명세서 나가게 해줘"
 *
 *  ★ 왜 ★
 *    업체 시트 「발주 및 송장조회」에는 «아직 안 받은» 줄이 섞여 있다 —
 *    코드가 틀렸거나, 품절이거나, 입력이 덜 된 줄이다. 그것이 명세서에
 *    실리면 업체는 «안 보낸 것»의 돈을 청구받는다.
 *
 *  ★ 여태는 「송장 있는 행만」이었다 ★
 *    그러면 발송완료만 실리고, 접수는 했는데 송장이 아직 안 붙은 줄이
 *    통째로 빠졌다. 그날 받은 것을 그날 보내는 일일 명세서에서는
 *    그게 대부분이다.
 *
 *  ★ 이 시험이 지키는 것 ★
 *    낱말이 «두 곳»에 있다 — 상태를 짓는 수식(_partnerHelpers.gs)과
 *    여기서 고르는 목록(_partnerTaxStatement.gs). 둘이 갈리면 명세서가
 *    «조용히» 빈다. 아무도 안 울고, 업체만 못 받는다. 그래서 맞대 본다.
 *
 *  실행: node _ptsstatus_test.js
 * ══════════════════════════════════════════════════════════════
 */

const fs = require("fs");

const PTS = fs.readFileSync("_partnerTaxStatement.gs", "utf8");
const HLP = fs.readFileSync("_partnerHelpers.gs", "utf8");

let 잰것 = 0, 틀린것 = 0;
function ok(이름, 참인가, 덧붙임) {
  잰것++;
  if (참인가) { console.log("  ok   " + 이름); return; }
  틀린것++;
  console.log("  FAIL " + 이름 + (덧붙임 ? "\n         " + 덧붙임 : ""));
}
function eq(이름, 얻은, 바란) {
  ok(이름 + "  →  " + JSON.stringify(얻은),
    JSON.stringify(얻은) === JSON.stringify(바란),
    "기대 " + JSON.stringify(바란));
}

/* ── [1] 고르는 목록 ─────────────────────────────────────── */
console.log("\n[1] 실을 수 있는 상태는 둘뿐");

const 목록줄 = (PTS.match(/var _PTS_OK_STATUS_ = \[[^\]]*\];/) || [""])[0];
ok("목록을 찾았다", 목록줄.length > 0);
const 고른것 = (목록줄.match(/"([^"]+)"/g) || []).map((s) => s.replace(/"/g, ""));
eq("★ 접수완료 · 발송완료", 고른것, ["접수완료", "발송완료"]);

/* ── [2] ★ 상태를 «짓는» 쪽과 같은 낱말인가 ★ ───────────── */
console.log("\n[2] 낱말이 두 곳에서 갈리지 않는다");

/*  N열 「상태(자동)」은 수식이 짓는다. 그 수식이 쓰는 낱말과 위 목록이
    어긋나면, 명세서는 «한 줄도» 안 실린 채 조용히 나간다.            */
const 수식 = (HLP.match(/function _pt_buildOrderStatusMapFormula_[\s\S]{0,1400}?\n\}/) || [""])[0];
ok("상태 수식을 찾았다", 수식.length > 0);
고른것.forEach(function (w) {
  ok("★ 수식이 「" + w + "」를 짓는다", 수식.indexOf('"' + w + '"') >= 0,
    "수식이 안 짓는 낱말을 고르면 명세서가 조용히 빈다");
});

/*  수식이 짓는 낱말 가운데 «우리가 안 고른 것»도 적어 둔다 —
    새 상태가 생겼는데 목록에 안 넣으면 그 건이 영영 안 실린다.      */
const 수식낱말 = Array.from(new Set(
  (수식.match(/"[^"]*"/g) || []).map((s) => s.replace(/"/g, ""))
)).filter((s) => /[가-힣]/.test(s) && s !== "상태(자동)" && s.indexOf("##") < 0);
const 뺀것 = 수식낱말.filter((w) => 고른것.indexOf(w) < 0);
console.log("      수식이 짓는 낱말: " + 수식낱말.join(" · "));
console.log("      그중 «안 싣는» 것: " + (뺀것.join(" · ") || "(없음)"));
ok("★ 안 싣는 것은 전부 «우리가 아직 안 받은» 줄이다",
  뺀것.every(function (w) {
    return /코드확인|단종|품절|재고까지만|입력미완|단종|^$/.test(w);
  }),
  "받은 줄인데 빠지면 업체가 못 받는다: " + 뺀것.join(" · "));

/* ── [3] 거르는 자리 ─────────────────────────────────────── */
console.log("\n[3] 거르는 자리가 제대로 박혔나");

const 거름 = (PTS.match(/if \(filter\.needInvoice\) \{[\s\S]{0,420}?\n    \}/) || [""])[0];
ok("거르는 자리를 찾았다", 거름.length > 0);
ok("★ 상태 칸이 있으면 상태로 가른다", /cMap\.status !== -1/.test(거름));
ok("★ 목록에 없으면 뺀다", /_PTS_OK_STATUS_\.indexOf\(상태\) < 0/.test(거름));
ok("  빈칸·공백에 안 속는다 (공백을 지우고 견준다)",
  /replace\(\/\\s\/g, ""\)/.test(거름));

/*  ★ 모르는 것을 「아니다」로 읽지 않는다 ★
    옛 탭에는 상태 칸이 없다. 칸이 없다고 전부 막으면 명세서가 통째로 빈다.  */
ok("★ 상태 칸이 없으면 여태대로 송장을 본다",
  /else if \(cMap\.invoice !== -1\)/.test(거름),
  "칸이 없다고 전부 막으면 명세서가 통째로 빕니다");

/* ── [4] 마감탭은 안 건드린다 ───────────────────────────── */
console.log("\n[4] 이미 나간 줄(마감탭)은 그대로 싣는다");
/*  거름은 filter.needInvoice 가 켜졌을 때만 돈다. 그것은 「마감」이 이름에
    없는 탭 — 즉 아직 안 나간 탭에만 켜진다. 마감탭은 이미 나간 줄이라
    상태 칸이 없거나 뜻이 달라, 거기까지 거르면 지난달 명세가 빈다.      */
ok("★ 거름은 needInvoice 안에서만 돈다", /if \(filter\.needInvoice\) \{/.test(PTS));
ok("  needInvoice 는 「마감」이 아닌 탭에만 켠다",
  /var live = names\[i\]\.indexOf\("마감"\) === -1;/.test(PTS) &&
  /needInvoice: live/.test(PTS));

/* ── [5] 가산 항목은 그대로 ─────────────────────────────── */
console.log("\n[5] 반품배송비·도서산간비는 여전히 다 더한다");
/*  가산 항목은 취소·반품 행도 포함해 전부 더한다 — 거름보다 «앞»에 있어야
    상태로 빠진 줄의 도서산간비도 살아남는다.                          */
const 가산자리 = PTS.indexOf('acc.extraSum["도서산간배송비"]');
const 거름자리 = PTS.indexOf("if (filter.needInvoice) {");
ok("★ 가산 더하기가 거름보다 «앞»이다", 가산자리 > 0 && 가산자리 < 거름자리,
  "뒤에 있으면 상태로 빠진 줄의 도서산간비가 같이 사라진다");

console.log("");
console.log(틀린것 ? "실패 " + 틀린것 + "건 / 통과 " + (잰것 - 틀린것)
                  : "모두 통과 (" + 잰것 + "건)");
process.exit(틀린것 ? 1 : 0);
