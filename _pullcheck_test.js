/**
 * ══════════════════════════════════════════════════════════════
 *  올리기 전 서버 견주기 — 판단 규칙
 *  2026-10-04
 *
 *  > "지금 파주에서 수정을 했는데 수정내용을 편집기로 커밋을 안하면
 *  >  일이 반복된다고 하네."
 *
 *  ★ 왜 시험이 있나 ★
 *    이 규칙이 느슨하면 편집기 작업이 조용히 덮인다(오류가 안 난다).
 *    빡빡하면 평소 배포가 다 막혀, 사람이 --서버무시 를 늘 붙이게 된다 —
 *    그러면 문이 있으나 없으나 같다. 둘 다 재야 한다.
 *
 *    세 번째 경우(서버에만 있다)는 서버를 건드려야 흉내 낼 수 있어
 *    실물로 못 재 본다. 그래서 규칙만 떼어 여기서 잰다.
 *
 *  돌리는 법   node _pullcheck_test.js
 * ══════════════════════════════════════════════════════════════
 */
const path = require("node:path");

let 잰것 = 0, 틀린것 = 0;
function ok(이름, 참인가, 덧붙임) {
  잰것++;
  if (참인가) { console.log("  ✔ " + 이름); return; }
  틀린것++;
  console.log("  ✗ " + 이름 + (덧붙임 ? "\n      " + 덧붙임 : ""));
}

(async () => {
  const { 판단 } = await import("file://" + path.join(__dirname, "_pullcheck.mjs").replace(/\\/g, "/"));

  console.log("─── 통과해야 하는 것 ───");
  ok("서버 == 작업 폴더 → 같다",
    판단("가", "가", "가") === "같다");
  ok("담긴 것도 다른데 서버 == 작업 폴더 → 같다",
    판단("나", "나", "가") === "같다",
    "둘이 같으면 올려도 덮을 게 없다. 담긴 것은 상관없다");
  ok("★ 평소 배포 ★ 내가 고쳤고 서버는 담긴 것 그대로 → 내가앞섰다",
    판단("나", "가", "가") === "내가앞섰다",
    "이것을 막으면 배포가 늘 막혀 사람이 --서버무시 를 달고 산다");

  console.log("\n─── 멈춰야 하는 것 ───");
  ok("★ 2026-10-04 의 사고 ★ 서버에 양쪽 다 없는 것이 있다 → 서버에만있다",
    판단("가", "다", "가") === "서버에만있다",
    "편집기에서 고친 것이 서버에만 있다. 올리면 조용히 없어진다");
  ok("내가 고쳤고 서버도 따로 고쳐졌다 → 서버에만있다",
    판단("나", "다", "가") === "서버에만있다",
    "양쪽이 갈라졌다. 기계가 고를 수 없으니 사람에게 넘긴다");
  ok("git 에 담긴 적 없는 파일이 서버와 다르다 → 서버에만있다",
    판단("가", "다", null) === "서버에만있다",
    "견줄 근거가 없다. 모르면 멈춘다");
  ok("담긴 적 없는데 서버와 같다 → 같다",
    판단("가", "가", null) === "같다",
    "같은 것은 담긴 적이 없어도 안전하다");

  console.log("\n─── 빈 값·흔한 함정 ───");
  ok("서버가 비었고 내 쪽에 있다 → 서버에만있다 (담긴 것이 없으면)",
    판단("가", "", null) === "서버에만있다",
    "서버가 빈 것은 사고일 수 있다 — 조용히 덮지 않는다");
  ok("서버가 비었고 담긴 것도 비었다 → 내가앞섰다",
    판단("가", "", "") === "내가앞섰다",
    "담긴 것이 빈 파일이면 서버가 그대로인 것이다");
  ok("셋이 다 비었다 → 같다", 판단("", "", "") === "같다");

  console.log("\n─── 쓰는 쪽에 붙어 있나 ───");
  const fs = require("node:fs");
  for (const [이름, 길] of [
    ["CS 웹앱 배포", "CS_WebApp/_csdeploy.mjs"],
    ["반품 포털 배포", "Partner_WebApp/_prpdeploy.mjs"],
  ]) {
    const s = fs.readFileSync(path.join(__dirname, 길), "utf8");
    ok(이름 + " 가 올리기 전에 본다", /서버먼저보기\(\)/.test(s) && /_pullcheck\.mjs/.test(s));
    //  ★ push 보다 «먼저» 불러야 한다 ★ 나중이면 이미 덮은 뒤다
    const 본자리 = s.indexOf("서버먼저보기()");
    const 민자리 = s.search(/\["push"/);
    ok(이름 + " 가 push 보다 먼저 본다", 본자리 >= 0 && 민자리 >= 0 && 본자리 < 민자리,
      "나중에 보면 이미 덮은 뒤다");
  }

  console.log("\n" + (틀린것 ? "✗ " : "✅ ") + 잰것 + "개 중 " + 틀린것 + "개 틀렸습니다.");
  process.exit(틀린것 ? 1 : 0);
})();
