/**
 * 전화주문 중복의심 — 같은 주문자 · 같은 상품명 · 같은 수량
 *
 *  > "세트분리에서 이전 판매현황을 비교해서 같은 주문(전화주문에서)도
 *  >  중복의심에 넣어줘. 4일치정도까지 찾아줘"
 *  > "같은 주문자 같은 상품명, 같은 수량.."   "전화주문의 경우 좀더 길게 보는거야"
 *  > "이카운트 중복주문(즉 사람의 실수)"
 *
 *  ★ 왜 전화주문«만» 인가 ★
 *    사방넷·주문서 건은 쇼핑몰이 준 주문번호가 있어서 「🔴 동일 고유ID」가 잡는다.
 *    전화주문은 사람이 이카운트에 손으로 넣으니 두 번 넣으면 번호가 둘이 된다.
 *    9/15 에 이름·전화·주소 등급을 지운 까닭(정상 재주문이 걸린다)은 여전히 맞다.
 *    그래서 «사람이 손으로 넣는 쪽»에만 되살린다.
 *
 *  실제 원장 7일치로 재 보니 하루 3.9묶음이다 — 사람이 볼 만한 크기다.
 *
 * 실행: node _ssdupphone_test.js
 */
const fs = require("fs"), path = require("path");
const core = require(path.join(__dirname, "세트분리V2", "core.js"));

let pass = 0, fail = 0;
function ok(label, cond, 덧) {
  if (cond) { pass++; console.log("  ✅ " + label); }
  else { fail++; console.log("  ❌ " + label + (덧 === undefined ? "" : "   " + 덧)); }
}

console.log("\n① 품목명에서 꼬리표를 뗀다 (같은 물건인데 다르게 보이면 못 잡는다)");
{
  const B = core.ssItemBase;
  ok("--- 꼬리표", B("AJ 감자탕 공용 200개---뚜껑만---법인/배민상회") === "AJ감자탕공용200개",
    B("AJ 감자탕 공용 200개---뚜껑만---법인/배민상회"));
  ok("=== 꼬리표", B("[샘플] JH 실링 12152 화이트 ===합포장") === "[샘플]JH실링12152화이트",
    B("[샘플] JH 실링 12152 화이트 ===합포장"));
  ok("=== 가 --- 보다 앞", B("가 ===합배송---뚜껑만") === "가", B("가 ===합배송---뚜껑만"));
  ok("꼬리표 없으면 그대로", B("TY 감자탕 왕대 100 SET") === "TY감자탕왕대100SET");
  ok("빈 값도 안 터진다", B("") === "" && B(null) === "");
}

/** 원장 줄 하나 */
function 줄(회차, uid, 누구, 품목, 수량, 출처) {
  return {
    회차: 회차, 고유ID: uid, 주문번호출처: 출처 || "자동발급",
    원본코드: "A" + 품목.length, 품목명: 품목, 경로: "로젠택배",
    받는분: 누구, 전화: "010-1111-2222", 모바일: "010-1111-2222",
    주소: "서울시 강남구 테헤란로 1", 수량: 수량, 금액: 10000,
  };
}
const 묶음찾기 = (rows) => {
  const f = core.ssFindDuplicates(rows);
  return f.groups.map((G) => ({
    grade: G.grade, reason: G.reason,
    ids: G.members.map((m) => f.records[m].고유ID),
  }));
};

console.log("\n② ★ 같은 회차에 같은 주문이 둘 — 이카운트 중복 입력 ★");
{
  //  실제로 있던 건이다 (260922-2 일호감자탕 윤용덕)
  const g = 묶음찾기([
    줄("260922-2", "p0922000018", "일호감자탕 윤용덕", "AJ 감자탕 공용 200개---뚜껑만", 2),
    줄("260922-2", "p0922000019", "일호감자탕 윤용덕", "AJ 감자탕 공용 200개---몸통만", 2),
  ]);
  ok("한 묶음으로 잡는다", g.length === 1, JSON.stringify(g));
  ok("등급이 「🟠 전화주문」", g[0] && g[0].grade === "🟠 전화주문", g[0] && g[0].grade);
  ok("★ 꼬리표가 달라도 같은 물건으로 본다", g[0] && g[0].ids.length === 2, JSON.stringify(g[0]));
}

console.log("\n③ 날을 넘겨도 잡는다 (4일 창은 부르는 쪽이 정한다)");
{
  const g = 묶음찾기([
    줄("260918-1", "p0918000003", "정가미감자탕 박준후", "TY 감자탕 왕대 100 SET", 1),
    줄("260922-1", "p0922000007", "정가미감자탕 박준후", "TY 감자탕 왕대 100 SET", 1),
  ]);
  ok("잡는다", g.length === 1 && g[0].grade === "🟠 전화주문", JSON.stringify(g));
}

console.log("\n④ ★ 사방넷·주문서 건은 «안» 잡는다 ★");
{
  //  쇼핑몰 건은 주문번호가 있어 「🔴 동일 고유ID」가 본다.
  //  여기까지 넓히면 목록이 정상 재주문으로 뒤덮인다 — 9/15 에 지운 까닭이다.
  const g = 묶음찾기([
    줄("260922-1", "2163978001", "청년다방 장상현", "BF 225파이 감자탕 소 200개", 4, "사방넷"),
    줄("260922-2", "2163978002", "청년다방 장상현", "BF 225파이 감자탕 소 200개", 4, "사방넷"),
  ]);
  ok("안 잡는다", g.length === 0, JSON.stringify(g));
}

console.log("\n⑤ 다른 것은 안 잡는다");
{
  const 경우 = [
    ["수량이 다르면", [
      줄("260922-1", "p1", "가게", "AJ 감자탕 공용 200개", 2),
      줄("260922-2", "p2", "가게", "AJ 감자탕 공용 200개", 3)]],
    ["물건이 다르면", [
      줄("260922-1", "p1", "가게", "AJ 감자탕 공용 200개", 2),
      줄("260922-2", "p2", "가게", "TY 감자탕 왕대 100 SET", 2)]],
    ["주문자가 다르면", [
      줄("260922-1", "p1", "가게하나", "AJ 감자탕 공용 200개", 2),
      줄("260922-2", "p2", "가게둘", "AJ 감자탕 공용 200개", 2)]],
    ["한 건뿐이면", [줄("260922-1", "p1", "가게", "AJ 감자탕 공용 200개", 2)]],
  ];
  경우.forEach(([이름, rows]) => {
    const g = 묶음찾기(rows).filter((x) => x.grade === "🟠 전화주문");
    ok(이름, g.length === 0, JSON.stringify(g));
  });
}

console.log("\n⑥ 비배송 줄은 애초에 안 본다 (적립금·할인은 물건이 아니다)");
{
  const a = 줄("260922-1", "p1", "가게", "적립금", 1);
  const b = 줄("260922-2", "p2", "가게", "적립금", 1);
  a.경로 = "비배송"; b.경로 = "비배송";
  ok("안 잡는다", 묶음찾기([a, b]).length === 0);
}

console.log("\n⑦ 같은 고유ID 는 여전히 「🔴 확실」이 본다");
{
  const g = 묶음찾기([
    줄("260922-1", "p0922000005", "가게", "AJ 감자탕 공용 200개", 2),
    줄("260922-2", "p0922000005", "가게", "AJ 감자탕 공용 200개", 2),
  ]);
  ok("🔴 로 잡는다", g.some((x) => x.grade === "🔴 확실"), JSON.stringify(g));
}

console.log("\n⑧ 배선 — 전화주문만 창이 넓다");
{
  const main = fs.readFileSync(path.join(__dirname, "세트분리V2", "gasMain.js"), "utf8");
  const io = fs.readFileSync(path.join(__dirname, "세트분리V2", "gasIO.js"), "utf8");
  ok("설정이 있다", /중복점검_대상일수_전화주문/.test(io));
  ok("기본 4일", /'중복점검_대상일수_전화주문', '4'/.test(io));
  ok("전화 창을 따로 만든다", /var 전화볼일수 = ssNum\(_cfg중복\['중복점검_대상일수_전화주문'\]\)/.test(main));
  ok("★ 일반 창보다 좁아지지 않게 막는다", /if \(전화볼일수 < 볼일수\) 전화볼일수 = 볼일수;/.test(main));
  ok("★ 줄을 담을 때 전화주문만 넓은 창을 쓴다",
    /_전화 \? 전화볼날\[_날6\] : 볼날\[_날6\]/.test(main));
}

console.log("\n" + (fail ? "❌ " + fail + "개 실패" : "✅ 모두 통과") + " (통과 " + pass + ")");
process.exit(fail ? 1 : 0);
