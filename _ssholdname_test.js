ok("9/28 오은수 줄 — 두 번 안 붙는다",
  이름("JH/BF 225파이 감자탕 공용 200개---뚜껑만---법인/배민상회", "법인/배민상회")
    === "JH/BF 225파이 감자탕 공용 200개---뚜껑만---법인/배민상회");
