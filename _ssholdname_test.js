function 이름그대로인가(원장줄들, 적힌원본, 보류에적힌이름) {
  let 그대로 = false;
  for (const L of 원장줄들) {
    if (L.원본 !== 적힌원본) continue;
    if (보류에적힌이름 && (L.이름 === 보류에적힌이름 || L.출력이름 === 보류에적힌이름)) 그대로 = true;
  }
  return 그대로;
}
