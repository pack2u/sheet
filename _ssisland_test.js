/**
 * 도서산간 판정 — 상호에 든 지역명에 안 걸린다
 *
 *  실제로 이렇게 나갔다 (260915 · 김세진 2줄):
 *    경기도 부천시 부흥로 315번길 55, 101,102,103호 제주은희네해장국
 *      → 권역[제주] · 경로[로젠택배-도서산간]
 *
 *  주소 «전체»에서 「제주」를 찾았기 때문이다. 상호는 주소 뒤에 붙어 오는데,
 *  「울릉도회관」·「완도수산」처럼 지역명이 든 상호는 흔하다 — 또 난다.
 *
 *  행정구역은 도로명·번지 «앞»에서 끝난다. 거기까지만 본다.
 *  실제 주소 3,316가지에 돌려 4가지만 달라졌다 — 전부 「제주은희네해장국」 체인이다.
 *
 * 실행: node _ssisland_test.js
 */
const path = require("path");
const core = require(path.join(__dirname, "세트분리V2", "core.js"));

let pass = 0, fail = 0;
function ok(label, cond, 덧) {
  if (cond) { pass++; console.log("  ✅ " + label); }
  else { fail++; console.log("  ❌ " + label + (덧 === undefined ? "" : "   " + 덧)); }
}
const 앞머리 = core.ssAddrRegion;

console.log("\n① ★ 상호의 지역명을 안 본다 ★  (실제로 잘못 나간 주소들)");
{
  const 나쁜것 = [
    "경기도 부천시 부흥로 315번길 55, 101,102,103호 제주은희네해장국",
    "경기도 파주시 교하로 557, 1층 제주은희네해장국 심학산점",
    "경기도 용인시 기흥구 언남동 255-22 1층 제주은희네해장국 구성",
    "경기도 파주시 청암로17번길 31 203호 제주은희네해장국 ( 목동동 )",
  ];
  나쁜것.forEach((a) => ok("제주가 안 남는다 — " + a.slice(0, 34),
    앞머리(a).indexOf("제주") < 0, 앞머리(a)));
}

console.log("\n② 진짜 섬은 그대로 남는다");
{
  const 섬 = [
    ["제주특별자치도 제주시 애월읍 상귀장수물길 14-1 장전리 제이유통 물류창고", "제주"],
    ["제주특별자치도 제주시 원노형5길 5", "제주"],
    ["제주특별자치도 제주시 월랑로4길 6노형동 더통큰집", "제주"],
    ["제주시 연동 261-11 1층", "제주"],
    ["서귀포시 대정읍 하모로 45", "서귀포"],
    ["경상북도 울릉군 울릉읍 도동2길 8", "울릉"],
  ];
  섬.forEach(([a, 낱말]) => ok(낱말 + " 가 남는다 — " + a.slice(0, 32),
    앞머리(a).indexOf(낱말) >= 0, 앞머리(a)));
}

console.log("\n③ 띄어쓰기가 없는 주소도 자른다");
{
  const a = "강원특별자치도인제군서화면서화길4-11";
  ok("인제군이 남는다", 앞머리(a).indexOf("인제군") >= 0, 앞머리(a));
  const b = "경기도고양시덕양구화중로138번길5-13 고양제주몸국";
  ok("★ 붙여 쓴 주소에서도 상호의 제주를 안 본다", 앞머리(b).indexOf("제주") < 0, 앞머리(b));
}

console.log("\n④ 지번 주소 — 아파트 이름에 든 지역명도 안 본다");
{
  //  「신안그린파크」의 신안은 아파트 이름이다
  const a = "경상북도 경주시 황성동 신안그린파크101동505호";
  ok("신안이 안 남는다", 앞머리(a).indexOf("신안") < 0, 앞머리(a));
  ok("  경주시는 남는다", 앞머리(a).indexOf("경주시") >= 0, 앞머리(a));
}

console.log("\n⑤ 너무 짧게 자르지 않는다 (시·도가 사라지면 안 된다)");
{
  const 것들 = [
    "서울 노원구 석계로 21 1층",
    "부산광역시 강서구 가덕해안로 783 (천성동) 중앙횟집2층",
    "인천 영종구 덕교동 105-3 1층",
    "거제시 고현동 98-27번지 고현종합시장내 충남식당",
  ];
  것들.forEach((a) => ok("시·군이 남는다 — " + a.slice(0, 26),
    /(시|군|구)/.test(앞머리(a)), 앞머리(a)));
  ok("빈 주소도 안 터진다", 앞머리("") === "" && 앞머리(null) === "");
}

console.log("\n⑥ 도선료표도 같은 규칙을 쓴다 (시군·읍면동은 앞머리, 리는 주소 전체)");
{
  const ferry = [{ 시군: "제주시", 읍면동: "애월읍", 리: ["장전리"], 료: 5000, 권역: "도서" }];
  //  「장전리」는 도로명 «뒤»에 온다 — 그래서 리는 주소 전체에서 찾아야 한다
  const a = "제주특별자치도 제주시 애월읍 상귀장수물길 14-1 장전리 제이유통 물류창고";
  ok("★ 도로명 뒤의 리도 찾는다", !!core.ssFerryMatch(a, ferry), JSON.stringify(core.ssFerryMatch(a, ferry)));

  //  상호에 「제주시 애월읍」이 들어간 엉뚱한 주소는 안 걸려야 한다
  const b = "경기도 부천시 부흥로 315번길 55 제주시애월읍칼국수 장전리점";
  ok("상호의 시군·읍면동에는 안 걸린다", core.ssFerryMatch(b, ferry) === null,
    JSON.stringify(core.ssFerryMatch(b, ferry)));
}

console.log("\n★ 도서산간 탭 「조치」 칸이 실제로 먹는다  (2026-09-28)");
{
  /*  > "도서산간에서 발송으로 처리 안했는데도 넘어가네.. 일부러 보류라고 적었는데도"

      여태 그 칸은 «아무 일도 하지 않았다». ss_섬조치걷기_ 가 걷어서 다시 써 주기만
      했다 — 재실행에 지워지지 않게 하려고 만든 것인데(2026-09-14), 적는 사람에게는
      「적으면 먹는 칸」으로 보인다. 적었는데 아무 일도 안 일어나는 칸은
      없는 것보다 나쁘다.  */
  const fs2 = require("fs");
  const src = fs2.readFileSync(path.join(__dirname, "세트분리V2", "core.js"), "utf8");
  const main = fs2.readFileSync(path.join(__dirname, "세트분리V2", "gasMain.js"), "utf8");

  ok("적은 말을 엔진이 읽는다", /cfg\._섬조치\[ssText\(u\.순번\) \+ .\|. \+ ssText\(u\.품목코드\)\]/.test(src));
  ok("  열쇠는 순번+품목코드다 (고유ID 는 세트 두 줄이 같다)",
    /ss_섬조치걷기_ 와 같은 열쇠/.test(src));
  ok("★ 「보류」면 세운다", /ssIslandHoldByManual_/.test(src) && /보류사유 = .도서산간확인./.test(src));
  ok("  도서산간 배정 «세 군데» 모두 앞에서 막는다",
    (src.split("if (_섬세우기) { ssIslandHoldByManual_(u, _섬적음); continue; }").length - 1) === 3,
    String(src.split("if (_섬세우기) { ssIslandHoldByManual_").length - 1));
  ok("★ 「발송」이면 도서산간에서 뺀다", /_섬적음 === .발송.\) 면제 = true;/.test(src));
  ok("  보류 탭의 「발송」이 더 세다 (거기는 세워 둔 줄을 푸는 자리다)",
    /!_섬세우기 && !면제 && _섬적음 === .발송./.test(src));
  ok("  세우는 말은 보류 탭과 «같은 목록»을 쓴다 (문법이 둘로 갈리지 않는다)",
    /SS_HOLD_KEEP_WORDS\[_sk\]/.test(src));
  ok("  얼마를 못 받는지 적어 준다", /추가운임 . \+ \(Number\(u\.도선료\)/.test(src));

  ok("★ 엔진 «앞»에서 걷는다 (판정에 쓰려면 먼저 손에 있어야 한다)",
    main.indexOf("cfg._섬조치 = ss_섬조치걷기_()") < main.indexOf("var res = ssRun(grid, masters, cfg)"));
  ok("★ 회차가 새것이어도 걷는다 (사람이 적은 말을 버릴 이유가 없다)",
    !/회차\.재실행 \? ss_섬조치걷기_\(\) : \{\}/.test(main));
  ok("  되돌려 쓸 때도 엔진에 넘긴 그것을 쓴다 (한 값에 주인은 하나)",
    /var 섬조치 = cfg\._섬조치 \|\| \{\};/.test(main));
  /*  ★ 고르개에 「대리발송」이 늘었다 ★  (2026-10-06 에 고침)
      코드는 ['발송','보류','대리발송'] 인데 시험이 둘만 기대해 빨갰다.
      어느 쪽이 맞나 — 조치 칸에 쓸 말은 발송·보류·업체코드다. 코드가 맞다.
      업체코드는 탭마다 달라 concat(codes) 로 붙으니 여기선 안 센다.
      ★ 낡아서 우는 시험을 두면 나머지 초록도 안 믿게 된다 ★            */
  ok("고르개를 단다", /ss_섬입력꾸미기_/.test(main) &&
    /requireValueInList\(\[.발송., .보류., .대리발송.\]/.test(main));
  ok("  칸 머리에 무슨 일이 일어나는지 적는다", /보류        보류\(미발송\) 탭으로 세웁니다/.test(main));
}

console.log("\n" + (fail ? "❌ " + fail + "개 실패" : "✅ 모두 통과") + " (통과 " + pass + ")");
process.exit(fail ? 1 : 0);
