console.log("\n⑥ 판매현황 칸 자리가 코드와 맞는가");
{
  const C = core.SS_SALES_COLS;
  const 칸 = (i) => String.fromCharCode(65 + i);
  ok("F 전화", C[5] === "전화", 칸(5) + " " + C[5]);
  ok("G 모바일", C[6] === "모바일", 칸(6) + " " + C[6]);
  ok("H 주소1", C[7] === "주소1", 칸(7) + " " + C[7]);
  ok("J 거래처명", C[9] === "거래처명", 칸(9) + " " + C[9]);
}

console.log("\n" + (fail ? "❌ " + fail + "개 실패" : "✅ 모두 통과") + " (통과 " + pass + ")");
process.exit(fail ? 1 : 0);
