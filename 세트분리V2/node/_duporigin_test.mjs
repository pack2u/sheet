/**
 * 중복의심 — 사방넷 건을 전화주문 잣대로 재지 않는다
 *
 *  > "중복의심에서 고유아이디와 이름과 품목코드 주문갯수를 먼져 보면 좋겠어..
 *  >  고유아이디가 다른데 중복의심이라고 뜨네..사방넷주문번호일경우..
 *  >  전화주문은 위내용으로 확인하면 조을꺼 같아
 *  >  전화주문은 세트분리에서 고유번호를 만들기떄문...."   (2026-09-16)
 *
 *  ★ 두 잣대가 있다 ★
 *    사방넷  — 주문번호를 쇼핑몰이 확정해 보낸다. 다르면 다른 주문이다. 끝.
 *    전화주문 — 고유ID 를 세트분리가 만든다(ssMakeOrderId). 전표번호·이름·
 *               연락처·주소·품목·수량을 섞은 해시라, 같은 주문을 전표번호만
 *               달리 해서 다시 적으면 다른 값이 나온다. ID 로는 못 가린다.
 *               그래서 이름 + 품목코드 + 수량 (+주소)이 지난 회차와 «줄줄이»
 *               같은가를 본다.
 *
 *  ssDupRunGroups 의 윗머리에는 「고유ID 를 안 쓴다 — 여기서 가리려는 것은
 *  전화주문처럼 고유ID 가 없는 줄」이라고 적혀 있었는데, 코드는 사방넷 줄까지
 *  세고 있었다. 적어 둔 뜻과 코드가 어긋나 있었던 것이다.
 *
 * 실행: node _duporigin_test.mjs
 */
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const C = require("../core.js");

let pass = 0, fail = 0;
const eq = (name, got, want) => {
  if (JSON.stringify(got) === JSON.stringify(want)) { pass++; console.log("  ok   " + name); }
  else { fail++; console.log("  FAIL " + name + "\n       got  " + JSON.stringify(got) +
    "\n       want " + JSON.stringify(want)); }
};

/** 원장 한 줄 흉내 */
function 줄(o) {
  return {
    회차: o.회차, 고유ID: o.고유ID || "", 주문번호출처: o.출처,
    원본코드: o.코드, 품목명: o.코드, 경로: "롯데택배",
    받는분: o.이름, 전화: o.전화 || "01011112222", 모바일: "",
    주소: o.주소 || "서울시 강남구 테헤란로 1", 수량: o.수량 == null ? 1 : o.수량, 금액: 1000,
  };
}

const 사 = C.SS_ORDNO_SRC.사방넷, 폰 = C.SS_ORDNO_SRC.자동발급;

console.log("\n[1] 사방넷 — 주문번호가 다르면 다른 주문이다");
{
  /*  어제와 오늘, 같은 사람이 같은 물건을 같은 수량으로 시켰다.
      이름·주소·품목·수량이 전부 같지만 사방넷 주문번호가 다르다.
      이건 «정상 재주문»이다. 중복이라고 하면 안 된다. */
  const rows = [
    줄({ 회차: "260915-1", 고유ID: "SB-1001", 출처: 사, 코드: "A1", 이름: "김철수" }),
    줄({ 회차: "260915-1", 고유ID: "SB-1002", 출처: 사, 코드: "B2", 이름: "김철수" }),
    줄({ 회차: "260916-1", 고유ID: "SB-2001", 출처: 사, 코드: "A1", 이름: "김철수" }),
    줄({ 회차: "260916-1", 고유ID: "SB-2002", 출처: 사, 코드: "B2", 이름: "김철수" }),
  ];
  const f = C.ssFindDuplicates(rows);
  const 이어짐 = C.ssDupRunGroups(f.records, "260916", 2);
  eq("★ 두 줄이 연속으로 같아도 사방넷이면 안 잡는다", 이어짐.length, 0);
  eq("등급 판정도 안 걸린다 (고유ID 가 다르다)", f.groups.length, 0);
}

console.log("\n[2] 사방넷 — 주문번호가 «같으면» 잡는다");
{
  //  같은 주문번호 + 같은 품목이 두 번. 붙여넣기를 두 번 했거나 두 번 돌린 것이다.
  const rows = [
    줄({ 회차: "260916-1", 고유ID: "SB-2001", 출처: 사, 코드: "A1", 이름: "김철수" }),
    줄({ 회차: "260916-2", 고유ID: "SB-2001", 출처: 사, 코드: "A1", 이름: "김철수" }),
  ];
  const f = C.ssFindDuplicates(rows);
  eq("★ 동일 고유ID + 품목은 그대로 잡는다", f.groups.length, 1);
  eq("등급", f.groups[0] && f.groups[0].grade, "🔴 확실");
  eq("사유", f.groups[0] && f.groups[0].reason, "동일 고유ID + 품목");
}

console.log("\n[3] 전화주문 — 이름 + 품목코드 + 수량이 줄줄이 같으면 잡는다");
{
  /*  붙여넣기 범위가 겹쳐 어제 것이 딸려온 모양. 고유ID 는 전표번호가 달라
      서로 다르게 나온다 — 그래서 ID 로는 못 가린다. */
  const rows = [
    줄({ 회차: "260915-1", 고유ID: "0915-PH-aaaa", 출처: 폰, 코드: "A1", 이름: "박영희" }),
    줄({ 회차: "260915-1", 고유ID: "0915-PH-bbbb", 출처: 폰, 코드: "B2", 이름: "박영희" }),
    줄({ 회차: "260916-1", 고유ID: "0916-PH-cccc", 출처: 폰, 코드: "A1", 이름: "박영희" }),
    줄({ 회차: "260916-1", 고유ID: "0916-PH-dddd", 출처: 폰, 코드: "B2", 이름: "박영희" }),
  ];
  const f = C.ssFindDuplicates(rows);
  const 이어짐 = C.ssDupRunGroups(f.records, "260916", 2);
  eq("★ 연속 두 줄을 잡는다", 이어짐.length, 1);
  eq("몇 줄이 이어졌나", 이어짐[0] && 이어짐[0].길이, 2);
  eq("어느 회차에서 딸려왔나", 이어짐[0] && 이어짐[0].이전회차, "260915-1");
}

console.log("\n[4] 전화주문 — 주문갯수가 다르면 다시 시킨 것이다");
{
  //  이름·품목은 같은데 수량이 다르다. 딸려온 것이 아니라 새로 시킨 것이다.
  const rows = [
    줄({ 회차: "260915-1", 고유ID: "0915-PH-aaaa", 출처: 폰, 코드: "A1", 이름: "박영희", 수량: 2 }),
    줄({ 회차: "260915-1", 고유ID: "0915-PH-bbbb", 출처: 폰, 코드: "B2", 이름: "박영희", 수량: 2 }),
    줄({ 회차: "260916-1", 고유ID: "0916-PH-cccc", 출처: 폰, 코드: "A1", 이름: "박영희", 수량: 5 }),
    줄({ 회차: "260916-1", 고유ID: "0916-PH-dddd", 출처: 폰, 코드: "B2", 이름: "박영희", 수량: 5 }),
  ];
  const f = C.ssFindDuplicates(rows);
  eq("★ 수량이 다르면 안 잡는다", C.ssDupRunGroups(f.records, "260916", 2).length, 0);
}

console.log("\n[5] 섞여 있어도 각자 잣대로 본다");
{
  const rows = [
    줄({ 회차: "260915-1", 고유ID: "SB-1001", 출처: 사, 코드: "A1", 이름: "김철수" }),
    줄({ 회차: "260915-1", 고유ID: "0915-PH-aaaa", 출처: 폰, 코드: "C3", 이름: "박영희" }),
    줄({ 회차: "260915-1", 고유ID: "0915-PH-bbbb", 출처: 폰, 코드: "D4", 이름: "박영희" }),
    줄({ 회차: "260916-1", 고유ID: "SB-2001", 출처: 사, 코드: "A1", 이름: "김철수" }),
    줄({ 회차: "260916-1", 고유ID: "0916-PH-cccc", 출처: 폰, 코드: "C3", 이름: "박영희" }),
    줄({ 회차: "260916-1", 고유ID: "0916-PH-dddd", 출처: 폰, 코드: "D4", 이름: "박영희" }),
  ];
  const f = C.ssFindDuplicates(rows);
  const 이어짐 = C.ssDupRunGroups(f.records, "260916", 2);
  eq("전화주문 두 줄만 잡힌다", 이어짐.length, 1);
  eq("잡힌 줄 수", 이어짐[0] && 이어짐[0].길이, 2);
  const 잡힌 = (이어짐[0] ? 이어짐[0].members : []).map((i) => f.records[i].주문번호출처);
  eq("★ 잡힌 줄은 전부 전화주문", 잡힌, [폰, 폰]);
}

console.log("\n[6] 출처를 모르는 옛 원장 줄은 «옛날처럼» 본다");
{
  /*  「주문번호출처」 칸이 없던 시절 원장에는 빈 값이 온다. 그때는 갈라 볼
      근거가 없으니 전화주문 잣대로 본다 — 안 보는 것보다 낫다.
      화면에는 「칸이 없다」고 적어 사람이 원장을 갱신하게 한다. */
  const rows = [
    줄({ 회차: "260915-1", 고유ID: "SB-1001", 출처: "", 코드: "A1", 이름: "김철수" }),
    줄({ 회차: "260915-1", 고유ID: "SB-1002", 출처: "", 코드: "B2", 이름: "김철수" }),
    줄({ 회차: "260916-1", 고유ID: "SB-2001", 출처: "", 코드: "A1", 이름: "김철수" }),
    줄({ 회차: "260916-1", 고유ID: "SB-2002", 출처: "", 코드: "B2", 이름: "김철수" }),
  ];
  const f = C.ssFindDuplicates(rows);
  eq("출처가 비면 예전처럼 잡는다", C.ssDupRunGroups(f.records, "260916", 2).length, 1);
}

console.log("\n[7] 중복의심 탭에 「번호출처」 칸이 보인다");
{
  eq("머리글에 있다", C.SS_DUP_HEADER.indexOf("번호출처") >= 0, true);
  eq("고유ID 바로 뒤", C.SS_DUP_HEADER.indexOf("번호출처"), C.SS_DUP_HEADER.indexOf("고유ID") + 1);
  const rows = [
    줄({ 회차: "260916-1", 고유ID: "SB-2001", 출처: 사, 코드: "A1", 이름: "김철수" }),
    줄({ 회차: "260916-2", 고유ID: "SB-2001", 출처: 사, 코드: "A1", 이름: "김철수" }),
  ];
  const out = C.ssDupRows(C.ssFindDuplicates(rows));
  eq("행 길이 = 머리글 길이", out[0].length, C.SS_DUP_HEADER.length);
  eq("그 칸에 출처가 적힌다", out[0][C.SS_DUP_HEADER.indexOf("번호출처")], 사);
}

console.log("");
console.log(fail === 0 ? "✅ 통과 " + pass + "건" : "❌ 실패 " + fail + "건 / 통과 " + pass + "건");
process.exit(fail === 0 ? 0 : 1);
