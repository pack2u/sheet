/**
 * 도서·제주 추가운임과 반품비.
 * ★ 2026-09-08
 *
 *   node node/_fee_test.mjs
 *
 * > "롯데 데이타를 기준으로 책정하게 해주고 반품시에는 +1000(박스비용)원을 더해서"
 * > "제주도 항공료 3000원 / 우도면, 추자면 항공료외 도선추가"
 *
 * ★ 항공료와 도선료는 더한다 ★
 *   둘 중 큰 것을 고르는 게 아니다. 비행기로 제주까지 간 뒤 배로 한 번 더 나간다.
 *   여기를 「max」로 짜면 우도·추자가 4,000원씩 덜 청구된다.
 */
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const C = require('../core.js');

let pass = 0, fail = 0;
const eq = (name, got, want) => {
  if (got === want) { pass++; console.log('  ok   ' + name); }
  else { fail++; console.log('  FAIL ' + name + '\n       got  ' + got + '\n       want ' + want); }
};

/** 시드와 같은 모양의 표 (gasSeed.js 발췌) */
const FERRY = [
  { 시군: '통영시', 읍면동: '욕지면', 리: [], 료: 4000, 권역: '도서' },
  { 시군: '통영시', 읍면동: '산양읍', 리: ['연곡리', '저림리', '추도리'], 료: 4000, 권역: '도서' },
  { 시군: '제주',   읍면동: '우도면', 리: [], 료: 4000, 권역: '제주' },
  { 시군: '제주',   읍면동: '추자면', 리: [], 료: 5000, 권역: '제주' },
];

console.log('\n[출고 추가운임]');
eq('육지는 0', C.ssSurcharge('서울 강남구 테헤란로 1', '', FERRY).합계, 0);
eq('통영 욕지면 = 도선료 4,000',
   C.ssSurcharge('경남 통영시 욕지면 동항리 100', '도서', FERRY).합계, 4000);
eq('★ 제주 본섬 = 항공료 3,000 (표에 없다) ★',
   C.ssSurcharge('제주특별자치도 제주시 노형동 1', '제주', FERRY).합계, 3000);
eq('★ 우도면 = 항공 3,000 + 도선 4,000 = 7,000 ★',
   C.ssSurcharge('제주특별자치도 제주시 우도면 연평리 1', '제주', FERRY).합계, 7000);
eq('★ 추자면 = 항공 3,000 + 도선 5,000 = 8,000 ★',
   C.ssSurcharge('제주특별자치도 제주시 추자면 대서리 1', '제주', FERRY).합계, 8000);

console.log('\n[권역을 안 넘겨도 도선료표가 말해 준다]');
eq('우도면은 표에 제주로 적혀 있다',
   C.ssSurcharge('제주시 우도면 연평리 1', '', FERRY).합계, 7000);
eq('욕지면은 도서라 항공료 없음',
   C.ssSurcharge('통영시 욕지면 동항리 1', '', FERRY).항공료, 0);

console.log('\n[리조건 — 그 읍·면 전체가 대상은 아니다]');
eq('산양읍 연곡리는 대상', C.ssSurcharge('통영시 산양읍 연곡리 12', '', FERRY).도선료, 4000);
eq('산양읍 삼덕리는 아님', C.ssSurcharge('통영시 산양읍 삼덕리 5', '', FERRY).도선료, 0);

console.log('\n[반품비 — 박스비 1,000 이 늘 붙는다]');
eq('★ 육지 반품도 1,000 ★', C.ssReturnFee('서울 강남구 테헤란로 1', '', FERRY).합계, 1000);
eq('욕지면 반품 = 4,000 + 1,000', C.ssReturnFee('통영시 욕지면 동항리 1', '도서', FERRY).합계, 5000);
eq('제주 본섬 반품 = 3,000 + 1,000',
   C.ssReturnFee('제주시 노형동 1', '제주', FERRY).합계, 4000);
eq('★ 우도면 반품 = 3,000 + 4,000 + 1,000 = 8,000 ★',
   C.ssReturnFee('제주시 우도면 연평리 1', '제주', FERRY).합계, 8000);
eq('★ 추자면 반품 = 3,000 + 5,000 + 1,000 = 9,000 ★',
   C.ssReturnFee('제주시 추자면 대서리 1', '제주', FERRY).합계, 9000);

console.log('\n[내역이 남는다 — 얼마를 왜 받았는지 말할 수 있어야 한다]');
const r = C.ssReturnFee('제주시 추자면 대서리 1', '제주', FERRY);
eq('항공료', r.항공료, 3000);
eq('도선료', r.도선료, 5000);
eq('박스비', r.박스비, 1000);
eq('근거', r.근거, '도선료표 추자면');

console.log('\n[값을 바꿔 부를 수 있다 — 요율이 오르면 표만 고친다]');
eq('항공료를 4,000 으로', C.ssSurcharge('제주시 노형동 1', '제주', FERRY, { 항공료: 4000 }).합계, 4000);
eq('박스비를 0 으로', C.ssReturnFee('서울 강남구 1', '', FERRY, { 박스비: 0 }).합계, 0);

/* ═══════════════════════════════════════════════════════════════
   세트 상품은 도서산간비가 두 배 — 2026-10-06
   > "세트분리에서도 세트 상품일경우 도서산간비 10000원"

   한글 「세트」는 몸통+뚜껑처럼 여러 박스가 따로 나가 택배비가 두 번 든다.
   영문 「SET」은 한 박스 완제품이라 한 값이다.

   ★ 품목명을 «넘겼을 때만» 갈린다 ★ 반품비(ssReturnFee)는 안 넘기므로
     여태 그대로다 — 반품은 「평균 비용으로 처리」라고 따로 정한 값이다.
   ═══════════════════════════════════════════════════════════════ */
console.log('\n[세트는 도서산간비 10,000 — 한글 「세트」만]');
const 섬 = (품목명) => C.ssSurcharge('제주시 노형동 1', '제주', FERRY,
  { 통일도선료: 5000, 세트도선료: 10000, 품목명 }).합계;
eq('보통 상품 5,000', 섬('JH 실링 23195 화이트 (100*1팩) 100'), 5000);
eq('한글 세트 10,000', 섬('BW 사출 195파이 특대 투명 300세트'), 10000);
eq('영문 SET 은 한 박스 — 5,000', 섬('JH 신형 105파이 중 블랙 1000 SET'), 5000);
eq('품목명이 없으면 한 값', 섬(''), 5000);
eq('세트금액을 안 넘기면 한 값 (끄는 법)',
  C.ssSurcharge('제주시 노형동 1', '제주', FERRY, { 통일도선료: 5000, 품목명: '300세트' }).합계, 5000);
eq('우도·추자도 세트면 10,000',
  C.ssSurcharge('제주시 추자면 대서리 1', '제주', FERRY,
    { 통일도선료: 5000, 세트도선료: 10000, 품목명: '300세트' }).합계, 10000);
eq('육지는 세트여도 0 — 붙는 줄에만 붙는다',
  C.ssSurcharge('서울 강남구 1', '', FERRY,
    { 통일도선료: 5000, 세트도선료: 10000, 품목명: '300세트' }).합계, 0);
eq('근거에 세트라고 적힌다',
  C.ssSurcharge('제주시 노형동 1', '제주', FERRY,
    { 통일도선료: 5000, 세트도선료: 10000, 품목명: '300세트' }).근거.indexOf('세트') === 0, true);

console.log('\n[반품비는 안 바뀐다 — 품목명을 안 넘긴다]');
eq('세트라도 반품비는 평균값 그대로',
  C.ssReturnFee('제주시 노형동 1', '제주', FERRY, { 통일도선료: 5000, 세트도선료: 10000 }).합계,
  C.ssReturnFee('제주시 노형동 1', '제주', FERRY, { 통일도선료: 5000 }).합계);

/* ★★ 허브와 «같은 금액»인가 ★★
   발주 수집(허브)은 _ISLAND_FEE_SET_ 로, 세트분리는 설정 「도선료_세트금액」으로
   정한다. 둘이 다르면 업체 시트(월마감 정산)와 이카운트가 서로 다른 돈을
   말한다 — 그건 조용하고, 달이 끝난 뒤에야 안 맞는 것이 드러난다.      */
console.log('\n[허브와 같은 금액인가]');
import fs from 'node:fs';
import path from 'node:path';
const 뿌리 = path.join(import.meta.dirname, '..', '..');
const 허브섬 = fs.readFileSync(path.join(뿌리, '_partnerIslandShipping.gs'), 'utf8');
const 허브세트 = Number((허브섬.match(/_ISLAND_FEE_SET_\s*=\s*(\d+)/) || [])[1]);
const 허브줄 = Number((허브섬.match(/_ISLAND_FEE_LINE_\s*=\s*(\d+)/) || [])[1]);
const 설정 = fs.readFileSync(path.join(뿌리, '세트분리V2', 'core.js'), 'utf8');
const 내세트 = Number((설정.match(/도선료_세트금액:\s*(\d+)/) || [])[1]);
const 내줄 = Number((설정.match(/도선료_통일금액:\s*(\d+)/) || [])[1]);
eq('세트 금액이 같다 (' + 허브세트 + ')', 내세트, 허브세트);
eq('한 줄 금액이 같다 (' + 허브줄 + ')', 내줄, 허브줄);
eq('세트 판정이 같은 잣대다 — 한글 「세트」',
  /indexOf\('세트'\) !== -1/.test(설정.slice(설정.indexOf('function ssIsSetName'))) &&
  /indexOf\("세트"\) !== -1/.test(허브섬.slice(허브섬.indexOf('function _island_isSetItem_'))), true);

console.log('\n' + (fail ? '실패 ' + fail + '건 / ' : '') + '통과 ' + pass + '건');
process.exit(fail ? 1 : 0);
