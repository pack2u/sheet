let 실패 = 0;
function ok(이름, 조건) {
  if (조건) { console.log("  ok   " + 이름); return; }
  실패++; console.log("  FAIL " + 이름);
}
function eq(이름, 실제, 기대) {
  const a = String(실제), b = String(기대);
  if (a === b) { console.log("  ok   " + 이름); return; }
  실패++; console.log("  FAIL " + 이름 + "  기대=" + b + "  실제=" + a);
}

