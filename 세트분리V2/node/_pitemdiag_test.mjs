/*  원장 한 줄을 이름으로 짓는다 — 자리로 박지 않는다  */
function 원장줄(HEAD, 값들) {
  const 행 = new Array(HEAD.length).fill("");
  for (const 이름 in 값들) 행[HEAD.indexOf(이름)] = 값들[이름];
  return 행;
}

