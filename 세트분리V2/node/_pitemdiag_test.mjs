function 가짜시트(rows) {
  return {
    rows,
    getLastRow: () => rows.length,
    getLastColumn: () => Math.max(...rows.map((r) => (r || []).length), 0),
    getRange(r, c, nr, nc) {
      return {
        getValues: () =>
          rows.slice(r - 1, r - 1 + nr).map((행) => {
            const 잘림 = (행 || []).slice(c - 1, c - 1 + nc);
            while (잘림.length < nc) 잘림.push("");
            return 잘림;
          }),
        setValues() {},
      };
    },
  };
}

