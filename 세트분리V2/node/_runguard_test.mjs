// 회차 검문 ssRunGuard — 사고 꼴은 걸리고 정상은 지나간다 (2026-10-22)
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const core = require('../core.js');
const G = core.ssRunGuard;
let ok = 0, ng = 0;
const 봄 = (이름, 참) => { if (참) ok++; else { ng++; console.log('✗', 이름); } };

const 줄 = (n, 길, 왜 = '', 상세 = '') => Array.from({ length: n }, (_, i) => ({ route: 길, 보류사유: 왜, 보류상세: 상세, 라인ID: String(100000 + i), 고유ID: 'u' + i }));

// ① 10/21 2차 사고 꼴 — 제 회차키(261021-2)와 겹친 이미출고 309줄
{
  const rows = [...줄(309, '보류', '이미출고', '261021-2 회차에 이미 나간 줄입니다'), ...줄(9, '보류', '제품아님', '금액 음수')];
  const g = G(rows, { 자기회차: ['M261021-2', '261021-2'] });
  봄('① 사고 꼴은 의심', g.의심 && g.셈.자기겹침 === 309);
}
// ② 라벨로만 적힌 자기 회차(M…)도
{
  const g = G(줄(50, '보류', '이미출고', 'M261021-2 회차에 이미 나간 줄입니다'), { 자기회차: ['261021-2'] });
  봄('② M 라벨도 자기', g.의심);
}
// ③ 하루치 통째 붙여넣기 — 다른 회차와 겹친 이미출고 477줄은 정상
{
  const rows = [...줄(288, '보류', '이미출고', 'M261020-2 회차에 이미 나간 줄입니다'), ...줄(189, '보류', '이미출고', '261020-1 회차에 이미 나간 줄입니다'), ...줄(130, '로젠택배')];
  const g = G(rows, { 자기회차: ['M261020-4', '261020-3'] });
  봄('③ 통째 붙여넣기는 통과', !g.의심);
}
// ④ 평범한 회차
봄('④ 평범', !G([...줄(300, '로젠택배'), ...줄(9, '보류', '제품아님')], { 자기회차: ['261021-1'] }).의심);
// ⑤ 마스터를 못 읽어 상태보류가 쏟아짐 (30%)
{
  const g = G([...줄(70, '로젠택배'), ...줄(30, '보류', '상태보류', '(상태 없음)')], {});
  봄('⑤ 상태보류 30% 는 의심', g.의심);
  봄('⑤ 8% 는 통과', !G([...줄(92, '로젠택배'), ...줄(8, '보류', '상태보류')], {}).의심);
}
// ⑥ 다시 돌기 — 조치 안 한 줄이 배송에서 보류로 20줄 → 의심 / 조치한 줄만 바뀌면 통과
{
  const 전 = {}; 줄(200, '로젠택배').forEach((r) => { 전[r.라인ID] = '로젠택배'; });
  const 지금 = 줄(200, '로젠택배'); for (let i = 0; i < 20; i++) { 지금[i].route = '보류'; 지금[i].보류사유 = '재고부족'; }
  봄('⑥ 말없이 20줄이 보류로 → 의심', G(지금, { 직전: 전 }).의심);
  봄('⑥ 그 20줄이 조치한 줄이면 통과', !G(지금, { 직전: 전, 조치고유ID: 지금.slice(0, 20).map((r) => r.고유ID) }).의심);
  const 셋 = 줄(200, '로젠택배'); for (let i = 0; i < 3; i++) 셋[i].route = '보류';
  봄('⑥ 3줄은 통과', !G(셋, { 직전: 전 }).의심);
  봄('⑥ 처음 도는 회차는 ㉰ 안 봄', !G(지금, { 직전: null }).의심);
}
// ⑦ 줄 0
봄('⑦ 0줄 의심', G([], {}).의심);

// ★ 깨 보기 — 자기회차를 안 넘기면 ① 이 안 걸린다(검문이 «자기회차»에 기대고 있다는 확인)
봄('깨기: 자기회차 없이 ① 은 안 걸림', !G(줄(309, '보류', '이미출고', '261021-2 회차에 이미 나간 줄입니다'), {}).의심);

console.log(ng ? `✗ ${ng}건 실패 · 통과 ${ok}` : `✅ 통과 ${ok}건`);
process.exit(ng ? 1 : 0);
