/**
 * ══════════════════════════════════════════════════════════════
 *  사방넷 주소 칸 — 이름이 바뀌어도 찾는다
 *  2026-10-06
 *
 *  > "세트분리에서 주소가 대량을 빠져 빨리 확인해줘"
 *  > "전화주문건만 주소가 들어오고 나머지가 주소가 뼈지네"
 *
 *  ★ 무엇이 일어났나 ★
 *    이카운트 판매현황의 사방넷 주소 칸 이름이 바뀌었다.
 *      오전 1차(261006-1)  「추가장문형식1」      → 멀쩡
 *      오후 2차(261006-2)  「배송지(사방넷)/배송메시지」 → 못 찾음
 *    2차 434줄 중 사방넷 340건의 주소가 통째로 빈 채 나갔다.
 *    전화주문 89건은 「주소1」에서 읽으므로 멀쩡했다 — 그래서 «일부만» 빠져 보였다.
 *
 *  ★ 왜 조용했나 ★
 *    이름으로 칸을 찾는다. 없으면 빈 문자열이 돌아오고 오류는 안 난다.
 *    2026-09-14 에도 같은 일이 있었다(「추가문자형7」 → 「추가장문형식1」).
 *    두 번 겪었으니 이름 목록만으로는 모자라다 — 느슨한 무늬를 같이 둔다.
 *
 *  ★ 이 시험이 지키는 것 ★
 *    ① 지금까지 쓰인 이름 셋을 다 찾는다
 *    ② 모르는 이름이어도 「배송지」와 「사방넷」이 같이 있으면 찾는다
 *    ③ ★ 주문서 칸을 «절대» 사방넷 주소로 집지 않는다 ★ — 그게 더 나쁜 사고다
 *    ④ 아는 이름이면 알림이 안 울린다 (매번 울리면 아무도 안 본다)
 *
 *  돌리는 법   node node/_sabangaddr_test.mjs
 * ══════════════════════════════════════════════════════════════
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const 여기 = dirname(fileURLToPath(import.meta.url));
const 코어경로 = join(여기, "..", "core.js");
const 코어글 = readFileSync(코어경로, "utf8");
const 상자 = { console };
vm.createContext(상자);
vm.runInContext(코어글, 상자);

let 잰것 = 0, 틀린것 = 0;
function ok(이름, 참, 덧) {
  잰것++;
  if (참) { console.log("  ok   " + 이름); return; }
  틀린것++;
  console.log("  FAIL " + 이름 + (덧 ? "  — " + 덧 : ""));
}
function 같나(이름, 얻은, 기대) {
  ok(이름, 얻은 === 기대, "얻은 " + JSON.stringify(얻은) + " · 기대 " + JSON.stringify(기대));
}

/*  core.js 가 쓰는 그 목록·무늬를 «코어 글에서 떼어 와» 쓴다.
    여기에 베껴 적으면 한쪽만 고쳐져서 시험이 통과하는데 실물은 안 되는 날이 온다. */
const 조각 = 코어글.match(/var 사방넷주소칸 = ssPickCol\(idx,\s*(\[[\s\S]*?\]),\s*(\/[\s\S]*?\/)\);/);
if (!조각) throw new Error("core.js 에서 사방넷주소칸 고르기를 못 찾았습니다");
const 후보들 = vm.runInContext(조각[1], 상자);
const 무늬 = vm.runInContext(조각[2], 상자);

function 고른다(머리글들) {
  const idx = {};
  머리글들.forEach((h, i) => { if (h) idx[h] = i; });
  return 상자.ssPickCol(idx, 후보들, 무늬);
}

/*  실제 판매현황 머리글 — 오늘 2차에서 그대로 가져온 것 */
const 공통 = ["순번", "일자-No.", "품목코드", "품목명", "수량", "전화", "모바일", "주소1",
  "합계", "거래처명", "세트구성및배송비", "단품배송비", "묶음배송비", "적요",
  "주문자명(사방넷)", "전화번호(사방넷)"];
const 꼬리 = ["주문자명(주문서)", "전화번호(주문서)", "배송지(주문서)/배송메시지(주문서)"];
const 판매현황 = (사방넷칸) => 공통.concat([사방넷칸], 꼬리);

console.log("\n[1] 지금까지 쓰인 이름을 다 찾는다");
같나("추가문자형7 (2026-09-14)", 고른다(판매현황("추가문자형7")), "추가문자형7");
같나("추가장문형식1 (오늘 오전 1차)", 고른다(판매현황("추가장문형식1")), "추가장문형식1");
같나("★ 배송지(사방넷)/배송메시지 (오늘 오후 2차) ★",
  고른다(판매현황("배송지(사방넷)/배송메시지")), "배송지(사방넷)/배송메시지");

console.log("\n[2] 모르는 이름도 무늬로 찾는다");
같나("추가문자형9 — 번호가 달라져도", 고른다(판매현황("추가문자형9")), "추가문자형9");
같나("사방넷배송지 — 괄호가 없어도", 고른다(판매현황("사방넷배송지")), "사방넷배송지");
같나("배송지 / 사방넷 — 차례가 바뀌어도", 고른다(판매현황("사방넷 배송지")), "사방넷 배송지");

console.log("\n[3] ★ 주문서 칸을 집으면 안 된다 ★");
//  사방넷 칸이 «아예 없는» 판매현황. 여기서 주문서 칸을 집으면 남의 주소가 송장에 찍힌다.
const 사방넷칸없음 = 공통.concat(꼬리);
같나("사방넷 칸이 없으면 «못 찾음»으로 둔다", 고른다(사방넷칸없음), "");
ok("배송지(주문서)/배송메시지(주문서) 는 무늬에 안 걸린다",
  !무늬.test("배송지(주문서)/배송메시지(주문서)"),
  "주문서 주소를 사방넷 주소로 쓰면 엉뚱한 곳으로 간다");
ok("주문자명(사방넷) 은 주소 칸이 아니다", !무늬.test("주문자명(사방넷)"));
ok("전화번호(사방넷) 도 주소 칸이 아니다", !무늬.test("전화번호(사방넷)"));

console.log("\n[4] 아는 이름이면 알림이 안 울린다");
const 아는이름 = 코어글.match(/\[\s*'추가문자형7',\s*'추가장문형식1',\s*'배송지\(사방넷\)\/배송메시지'\s*\]\.indexOf\(사방넷주소칸\) < 0/);
ok("아는 이름 셋은 주의 알림에서 뺀다", !!아는이름,
  "매번 울리는 알림은 아무도 안 본다 — 그러면 진짜 바뀐 날도 묻힌다");
ok("모르는 이름이면 그래도 말한다", /아는 이름이 아닙니다/.test(코어글));
ok("아예 못 찾으면 «오류»로 말한다", /SABANG_ADDR_COL', '\(못 찾음\)'/.test(코어글));
ok("못 찾았을 때 실제 머리글을 같이 싣는다", /판매현황 머리글: ' \+ 본이름\.join/.test(코어글));

console.log("\n[5] 전화주문은 늘 「주소1」에서 읽는다 (이번에 멀쩡했던 길)");
ok("출처가 이카운트면 주소1", /주소원본 = g\(row, '주소1'\)/.test(코어글));
ok("출처가 사방넷이면 고른 칸", /g\(row, 사방넷주소칸\)/.test(코어글));
ok("출처가 주문서면 주문서 칸",
  /g\(row, '배송지\(주문서\)\/배송메시지\(주문서\)'\)/.test(코어글));

console.log("\n" + (틀린것 ? "✗ " + 잰것 + "개 중 " + 틀린것 + "개 틀렸습니다."
  : "✅ " + 잰것 + "개 모두 통과."));
process.exit(틀린것 ? 1 : 0);
